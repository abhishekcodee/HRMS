// Function 4: Send Salary Slip Email with Attachment (Duplicate Protected)
export async function sendSalarySlipEmail(payload: SalarySlipEmailPayload): Promise<{ success: boolean; logId: string; error?: string }> {
  const logId = uuidv4();
  const subject = `Salary Slip - ${payload.salaryMonth} ${payload.salaryYear}`;

  // Duplicate protection check on (employee_id, salary_month, salary_year)
  const [existing]: any = await pool.query(
    `SELECT id FROM salary_slip_email_logs WHERE employee_id = ? AND salary_month = ? AND salary_year = ? AND status = 'SENT'`,
    [payload.employeeId, payload.salaryMonth, payload.salaryYear]
  );
  if (existing.length > 0) {
    return { success: false, logId: existing[0].id, error: `Salary slip already sent for ${payload.employeeId} (${payload.salaryMonth} ${payload.salaryYear}).` };
  }

  // Validate Email
  if (!isValidEmail(payload.employeeEmail)) {
    const errorMsg = `Invalid or missing employee email address: ${payload.employeeEmail || 'N/A'}`;
    await pool.query(
      `INSERT INTO salary_slip_email_logs (id, employee_id, employee_email, salary_month, salary_year, salary_slip_file, email_subject, status, error_message)
       VALUES (?, ?, ?, ?, ?, ?, ?, 'FAILED', ?)
       ON DUPLICATE KEY UPDATE status = 'FAILED', error_message = ?, updated_at = NOW()`,
      [logId, payload.employeeId, payload.employeeEmail || 'N/A', payload.salaryMonth, payload.salaryYear, payload.salarySlipFilePath || 'N/A', subject, errorMsg, errorMsg]
    );
    return { success: false, logId, error: errorMsg };
  }

  const htmlContent = renderSalarySlipTemplate(payload);

  const attachments: any[] = [];
  if (payload.attachmentBuffer) {
    attachments.push({
      filename: payload.attachmentFilename || `Salary_Slip_${payload.employeeId}_${payload.salaryMonth}_${payload.salaryYear}.pdf`,
      content: payload.attachmentBuffer,
    });
  } else if (payload.salarySlipFilePath) {
    attachments.push({
      filename: payload.attachmentFilename || `Salary_Slip_${payload.employeeId}_${payload.salaryMonth}_${payload.salaryYear}.pdf`,
      path: payload.salarySlipFilePath,
    });
  }

  try {
    const transporter = getSmtpTransporter();
    await transporter.sendMail({
      from: `"${fromName}" <${fromAddress}>`,
      to: payload.employeeEmail,
      subject,
      html: htmlContent,
      attachments,
    });

    await pool.query(
      `INSERT INTO salary_slip_email_logs (id, employee_id, employee_email, salary_month, salary_year, salary_slip_file, email_subject, status, sent_at)
       VALUES (?, ?, ?, ?, ?, ?, ?, 'SENT', NOW())
       ON DUPLICATE KEY UPDATE status = 'SENT', sent_at = NOW(), error_message = NULL, updated_at = NOW()`,
      [logId, payload.employeeId, payload.employeeEmail, payload.salaryMonth, payload.salaryYear, payload.salarySlipFilePath || 'Attached', subject]
    );

    return { success: true, logId };
  } catch (error: any) {
    logger.error('Failed to send Salary Slip email:', error);
    await pool.query(
      `INSERT INTO salary_slip_email_logs (id, employee_id, employee_email, salary_month, salary_year, salary_slip_file, email_subject, status, error_message)
       VALUES (?, ?, ?, ?, ?, ?, ?, 'FAILED', ?)
       ON DUPLICATE KEY UPDATE status = 'FAILED', error_message = ?, updated_at = NOW()`,
      [logId, payload.employeeId, payload.employeeEmail, payload.salaryMonth, payload.salaryYear, payload.salarySlipFilePath || 'Attached', subject, error.message, error.message]
    );
    return { success: false, logId, error: error.message };
  }
}

// Function 5: Retry Failed Email
export async function retryFailedNotification(notificationId: string): Promise<{ success: boolean; message: string }> {
  const [rows]: any = await pool.query(
    `SELECT id, employee_id, leave_request_id, recipient_email, email_type, subject, retry_count FROM email_notifications WHERE id = ?`,
    [notificationId]
  );

  if (rows.length === 0) {
    return { success: false, message: 'Notification log entry not found.' };
  }

  const item = rows[0];

  try {
    const transporter = getSmtpTransporter();
    await transporter.sendMail({
      from: `"${fromName}" <${fromAddress}>`,
      to: item.recipient_email,
      subject: item.subject,
      html: `<div style="font-family: Arial; padding: 20px;"><h3>Notification Re-send</h3><p>This is a retry notification for request ${item.leave_request_id || item.employee_id}.</p></div>`,
    });

    await pool.query(
      `UPDATE email_notifications SET status = 'SENT', sent_at = NOW(), error_message = NULL, retry_count = retry_count + 1 WHERE id = ?`,
      [notificationId]
    );
    return { success: true, message: `Email re-sent successfully to ${item.recipient_email}` };
  } catch (err: any) {
    await pool.query(
      `UPDATE email_notifications SET status = 'FAILED', error_message = ?, retry_count = retry_count + 1 WHERE id = ?`,
      [err.message, notificationId]
    );
    return { success: false, message: `Retry failed: ${err.message}` };
  }
}
