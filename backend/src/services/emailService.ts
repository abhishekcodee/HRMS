// Function 1: Send Leave Applied Email to HR
export async function sendLeaveAppliedEmail(payload: LeaveEmailPayload): Promise<{ success: boolean; notificationId: string; error?: string }> {
  const notificationId = uuidv4();
  const hrTargetEmail = payload.hrEmail || process.env.HR_EMAIL || 'employer@hrms.com';
  const subject = `New Leave Request: ${payload.employeeName} (${payload.leaveType})`;

  // Duplicate Check
  const [existing]: any = await pool.query(
    `SELECT id FROM email_notifications WHERE leave_request_id = ? AND email_type = 'LEAVE_APPLIED' AND status = 'SENT'`,
    [payload.leaveRequestId]
  );
  if (existing.length > 0) {
    logger.info(`[Email Skip] Leave Applied email already sent for request ${payload.leaveRequestId}`);
    return { success: true, notificationId: existing[0].id };
  }

  // Validate Email
  if (!isValidEmail(hrTargetEmail)) {
    const errorMsg = `Invalid HR email address: ${hrTargetEmail}`;
    await pool.query(
      `INSERT INTO email_notifications (id, employee_id, leave_request_id, recipient_email, email_type, subject, status, error_message)
       VALUES (?, ?, ?, ?, ?, ?, 'FAILED', ?)`,
      [notificationId, payload.employeeId, payload.leaveRequestId, hrTargetEmail, 'LEAVE_APPLIED', subject, errorMsg]
    );
    return { success: false, notificationId, error: errorMsg };
  }

  const hrmsUrl = process.env.FRONTEND_URL || 'http://localhost:5173';
  const htmlContent = renderLeaveAppliedTemplate(payload, hrmsUrl);

  try {
    const transporter = getSmtpTransporter();
    await transporter.sendMail({
      from: `"${fromName}" <${fromAddress}>`,
      to: hrTargetEmail,
      subject,
      html: htmlContent,
    });

    await pool.query(
      `INSERT INTO email_notifications (id, employee_id, leave_request_id, recipient_email, email_type, subject, status, sent_at)
       VALUES (?, ?, ?, ?, ?, ?, 'SENT', NOW())`,
      [notificationId, payload.employeeId, payload.leaveRequestId, hrTargetEmail, 'LEAVE_APPLIED', subject]
    );

    return { success: true, notificationId };
  } catch (error: any) {
    logger.error('Failed to send Leave Applied email:', error);
    await pool.query(
      `INSERT INTO email_notifications (id, employee_id, leave_request_id, recipient_email, email_type, subject, status, error_message)
       VALUES (?, ?, ?, ?, ?, ?, 'FAILED', ?)`,
      [notificationId, payload.employeeId, payload.leaveRequestId, hrTargetEmail, 'LEAVE_APPLIED', subject, error.message]
    );
    return { success: false, notificationId, error: error.message };
  }
}

