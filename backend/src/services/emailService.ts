// 1. Centralized SMTP Transport configuration
function getSmtpTransporter() {
  const host = process.env.MAIL_HOST || 'smtp.gmail.com';
  const port = parseInt(process.env.MAIL_PORT || '587', 10);
  const secure = process.env.MAIL_ENCRYPTION === 'ssl' || port === 465;
  const user = process.env.MAIL_USERNAME || '';
  const pass = process.env.MAIL_PASSWORD || '';

  if (!user || !pass) {
    // Development / Dry-run Transport fallback
    return {
      isDryRun: true,
      sendMail: async (mailOptions: any) => {
        logger.info(`[SMTP DRY RUN] Email would be sent to: ${mailOptions.to} | Subject: "${mailOptions.subject}"`);
        return { messageId: `dry-run-${Date.now()}` };
      },
    };
  }

  const transporter = nodemailer.createTransport({
    host,
    port,
    secure,
    auth: {
      user,
      pass,
    },
    tls: {
      rejectUnauthorized: false,
    },
  });

  return { isDryRun: false, sendMail: (opts: any) => transporter.sendMail(opts) };
}

